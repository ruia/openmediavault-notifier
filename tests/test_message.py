import unittest

from omvnotifier.message import EVENT_CLASSES, EVENT_TITLES, classify, test_notification

from helpers import MONIT_FS_BODY, MONIT_FS_SUBJECT


class MonitTest(unittest.TestCase):
    def test_filesystem_recovery(self):
        notification = classify(MONIT_FS_SUBJECT, MONIT_FS_BODY, hostname="storagecenter")
        self.assertEqual(notification.event, "monit-filesystem")
        self.assertTrue(notification.recovery)
        self.assertEqual(notification.severity, "info")
        self.assertEqual(notification.subject, MONIT_FS_SUBJECT.split("] ", 1)[1])
        self.assertEqual(
            notification.fields["service"],
            "filesystem_srv_dev-disk-by-uuid-01fd2738-e207-4442-b826-a6ac1025953a",
        )
        self.assertEqual(notification.fields["event"], "Resource limit succeeded")
        self.assertIn("92.4%", notification.fields["description"])
        self.assertEqual(notification.fields["action"], "alert")
        self.assertNotIn("date", notification.fields)

    def test_filesystem_alert(self):
        body = MONIT_FS_BODY.replace("Resource limit succeeded", "Resource limit matched")
        notification = classify(
            "Monitoring alert -- Resource limit matched filesystem_srv_dev-disk-by-uuid-x", body
        )
        self.assertEqual(notification.event, "monit-filesystem")
        self.assertFalse(notification.recovery)
        self.assertEqual(notification.severity, "warning")

    def test_rootfs_and_mountpoint_checks(self):
        for service in ("rootfs", "mountpoint_srv_dev-disk-by-uuid-x"):
            notification = classify(f"Monitoring alert -- Status failed {service}", "")
            self.assertEqual(notification.event, "monit-filesystem", service)

    def test_resource_alert_on_system_check(self):
        body = "Service:     storagecenter\nEvent:       Resource limit matched\n" \
               "Description: cpu user usage of 97.0% matches resource limit [cpu user usage > 95.0%]\n"
        notification = classify(
            "Monitoring alert -- Resource limit matched storagecenter", body, hostname="storagecenter"
        )
        self.assertEqual(notification.event, "monit-resource")
        self.assertEqual(notification.severity, "warning")
        self.assertFalse(notification.recovery)

    def test_process_failure_is_critical(self):
        notification = classify("Monitoring alert -- Does not exist nginx", "Service: nginx\nEvent: Does not exist\n")
        self.assertEqual(notification.event, "monit-process")
        self.assertEqual(notification.severity, "critical")

    def test_process_recovery(self):
        notification = classify("Monitoring alert -- Exists nginx", "Service: nginx\nEvent: Exists\n")
        self.assertEqual(notification.event, "monit-process")
        self.assertTrue(notification.recovery)
        self.assertEqual(notification.severity, "info")


class OtherSourcesTest(unittest.TestCase):
    def test_smart(self):
        body = "This message was generated by the smartd daemon running on:\n\n" \
               "   host name:  storagecenter\n\nThe following warning/error was logged by the smartd daemon:\n\n" \
               "Device: /dev/sda [SAT], 8 Currently unreadable (pending) sectors\n\n" \
               "Device info:\nWDC WD40EFRX-68N32N0, S/N:WD-WCC7K1234567, WWN:5-0014ee-2b9c0e6a3, FW:82.00A82, 4.00 TB\n"
        notification = classify("SMART error (CurrentPendingSector) detected on host: storagecenter", body)
        self.assertEqual(notification.event, "smart")
        self.assertEqual(notification.severity, "critical")
        self.assertEqual(notification.fields["device"], "/dev/sda")
        self.assertEqual(notification.fields["type"], "CurrentPendingSector")
        self.assertTrue(notification.fields["deviceinfo"].startswith("WDC WD40EFRX"))

    def test_smart_temperature_is_warning(self):
        notification = classify("SMART error (Temperature) detected on host: nas", "")
        self.assertEqual(notification.severity, "warning")

    def test_mdadm_degraded(self):
        notification = classify("DegradedArray event on /dev/md0:storagecenter", "")
        self.assertEqual(notification.event, "mdadm")
        self.assertEqual(notification.severity, "critical")
        self.assertEqual(notification.fields["device"], "/dev/md0")
        self.assertFalse(notification.recovery)

    def test_mdadm_rebuild_finished_is_recovery(self):
        notification = classify("RebuildFinished event on /dev/md127:nas", "")
        self.assertEqual(notification.severity, "info")
        self.assertTrue(notification.recovery)

    def test_updates(self):
        notification = classify("[nas] 12 package update(s) available", "")
        self.assertEqual(notification.event, "updates")
        self.assertEqual(notification.fields["count"], "12")
        self.assertEqual(classify("No package updates available", "").fields["count"], "0")

    def test_cron_with_name(self):
        notification = classify("Cron - Nightly backup", "done\n")
        self.assertEqual(notification.event, "cron")
        self.assertEqual(notification.fields["name"], "Nightly backup")
        self.assertEqual(classify("Cron", "").event, "cron")
        self.assertEqual(classify("Cron <root@nas> /usr/bin/true", "").event, "cron")

    def test_auth(self):
        self.assertEqual(classify("Locked users overview", "").event, "auth")
        self.assertEqual(classify("Login from 10.0.0.5", "").severity, "warning")

    def test_system(self):
        self.assertEqual(classify("Reboot required", "").event, "system")
        self.assertEqual(classify("Errors were detected on the file system mounted at /srv/x [UUID=y]", "").severity, "critical")
        self.assertEqual(classify("Scrub report of the file system mounted at /srv/x [UUID=y]", "").severity, "info")
        self.assertEqual(classify("Test message from nas", "").event, "system")

    def test_unknown(self):
        notification = classify("Something else entirely", "body")
        self.assertEqual(notification.event, "unknown")
        self.assertEqual(notification.severity, "info")
        self.assertEqual(notification.fields, {})

    def test_empty_subject(self):
        self.assertEqual(classify("", "").subject, "")


class EventClassesTest(unittest.TestCase):
    def test_classes_are_unique_and_titled(self):
        keys = [key for key, _ in EVENT_CLASSES]
        self.assertEqual(len(keys), len(set(keys)))
        self.assertTrue(all(EVENT_TITLES[key] for key in keys))

    def test_test_notification(self):
        notification = test_notification("nas.local")
        self.assertEqual(notification.event, "system")
        self.assertIn("nas.local", notification.body)


if __name__ == "__main__":
    unittest.main()
